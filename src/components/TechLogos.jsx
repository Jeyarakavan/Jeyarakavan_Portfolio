export const TechLogo = ({ name, ...props }) => {
  const normalized = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (normalized.includes('python')) return <PythonLogo {...props} />;
  if (normalized.includes('tensorflow')) return <TensorFlowLogo {...props} />;
  if (normalized.includes('pytorch') || normalized.includes('keras') || normalized.includes('learning')) return <PyTorchLogo {...props} />;
  if (normalized.includes('react') || normalized.includes('javascript') || normalized.includes('typescript')) return <ReactLogo {...props} />;
  if (normalized.includes('node') || normalized.includes('backend') || normalized.includes('api')) return <NodeLogo {...props} />;
  if (normalized.includes('java') || normalized.includes('spring')) return <JavaLogo {...props} />;
  if (normalized.includes('design') || normalized.includes('ui') || normalized.includes('figma')) return <FigmaLogo {...props} />;
  if (normalized.includes('data') || normalized.includes('science') || normalized.includes('sql') || normalized.includes('analysis')) return <DataLogo {...props} />;
  if (normalized.includes('cloud') || normalized.includes('micro') || normalized.includes('docker') || normalized.includes('kubernetes') || normalized.includes('aws')) return <CloudLogo {...props} />;
  return <CloudLogo {...props} />; // Fallback
};

